import math

#Using ceil function 
print("The ceil value of -43.59 is: ",math.ceil(-43.59))
#Using floor function
print("The floor value of 11.23 is: ",math.floor(11.23))
#Using copysign function
print("The copysign value of -5 and 3 is: ",math.copysign(-5,3))
#Using absolute function
print("The absolute value of -83 and 6 is: ",math.fabs(-83),math.fabs(6))
#Using GCD function
print("The GCD value of 12 and 15 is: ",math.gcd(12,15))